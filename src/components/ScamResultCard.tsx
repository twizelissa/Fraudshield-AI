"use client";

import { useState } from "react";
import {
  AlertTriangle,
  CheckCircle,
  Copy,
  ThumbsUp,
  ThumbsDown,
  RotateCcw,
  Info,
  Shield,
  Briefcase,
  GraduationCap,
  Building2,
  Link2Off,
  DollarSign,
  Heart,
  Package,
  AlertCircle,
  HelpCircle,
  Check,
  FileWarning,
  Mail,
  ShieldCheck,
  Terminal,
  Globe,
  ExternalLink,
  Database,
  Calendar,
  MapPin,
  User,
} from "lucide-react";
import { ScamAnalysis } from "@/types/fraudshield";
import RiskGauge from "./RiskGauge";

interface ScamResultCardProps {
  result: ScamAnalysis & {
    id: string;
    matchingReports?: {
      id: string;
      reportedMessage: string;
      category: string | null;
      country: string | null;
      userEmail: string | null;
      createdAt: string;
    }[];
  };
  onReset: () => void;
}

const categoryIconMap: Record<string, React.ComponentType<{ className?: string }>> = {
  "fake job": Briefcase,
  "job": Briefcase,
  "fake scholarship": GraduationCap,
  "scholarship": GraduationCap,
  "fake grant": Building2,
  "grant": Building2,
  "phishing": Link2Off,
  "link": Link2Off,
  "fake investment": DollarSign,
  "investment": DollarSign,
  "finance": DollarSign,
  "romance/social scam": Heart,
  "romance": Heart,
  "social scam": Heart,
  "fake delivery/payment scam": Package,
  "delivery": Package,
  "payment": Package,
  "general suspicious message": AlertCircle,
  "suspicious sms": FileWarning,
  "sms": FileWarning,
  "whatsapp": FileWarning,
  "email": Mail,
  "unknown": HelpCircle,
};

function CategoryIcon({ category, className }: { category: string; className?: string }) {
  const normalized = category.toLowerCase().trim();
  let Icon: React.ComponentType<{ className?: string }> = Shield;
  for (const [key, iconComp] of Object.entries(categoryIconMap)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      Icon = iconComp;
      break;
    }
  }
  return <Icon className={className} />;
}

function GroundingSourceItem({ text }: { text: string }) {
  const urlRegex = /(https?:\/\/[^\s]+)/g;
  const match = text.match(urlRegex);

  if (match) {
    const url = match[0];
    const label =
      text.replace(url, "").trim().replace(/^[-:–]\s*/, "").replace(/\s*[-:–]$/, "") ||
      "Verification Source";

    return (
      <div className="flex items-center justify-between gap-2 px-3 py-2 rounded-xl bg-[#FAF8F5] border border-[#E5E0D8]">
        <div className="flex items-center gap-2 min-w-0">
          <Globe className="h-3.5 w-3.5 text-[#11382B] shrink-0" />
          <span className="text-xs text-black font-bold truncate">{label}</span>
        </div>
        <a
          href={url}
          target="_blank"
          rel="noopener noreferrer"
          className="text-xs text-[#11382B] font-bold hover:underline shrink-0 flex items-center gap-1"
        >
          Source
          <ExternalLink className="h-3 w-3" />
        </a>
      </div>
    );
  }

  return (
    <div className="flex items-start gap-2 text-xs text-black font-semibold">
      <Globe className="h-3.5 w-3.5 text-[#11382B] shrink-0 mt-0.5" />
      <span>{text}</span>
    </div>
  );
}

function getConfidenceColor(level: string) {
  switch (level) {
    case "High":
      return "text-[#166534] bg-[#F0FDF4] border-[#BBF7D0]";
    case "Medium":
      return "text-[#92400E] bg-[#FEF3C7] border-[#FDE68A]";
    default:
      return "text-black bg-[#FAF8F5] border-[#E5E0D8]";
  }
}

const redactEmail = (email: string | null) => {
  if (!email) return "Anonymous Submitter";
  const parts = email.split("@");
  if (parts.length !== 2) return "Redacted Operator";
  const [username, domain] = parts;
  if (username.length <= 2) {
    return `${username}***@${domain}`;
  }
  return `${username.slice(0, 2)}***@${domain}`;
};

export default function ScamResultCard({ result, onReset }: ScamResultCardProps) {
  const [copied, setCopied] = useState(false);
  const [feedbackSent, setFeedbackSent] = useState(false);
  const [feedbackLoading, setFeedbackLoading] = useState(false);

  const isHighRisk = result.risk_level === "High Risk";
  const isMediumRisk = result.risk_level === "Medium Risk";

  const statusColor = isHighRisk
    ? "bg-[#FEF2F2] border-[#FCA5A5] text-[#991B1B]"
    : isMediumRisk
      ? "bg-[#FEF3C7] border-[#FDE68A] text-[#92400E]"
      : "bg-[#F0FDF4] border-[#BBF7D0] text-[#166534]";

  const handleCopy = async () => {
    const report = `
FraudShield Security Report
======================================
Report ID: ${result.id}
Risk Score: ${result.risk_score}/100
Risk Level: ${result.risk_level}
Category: ${result.scam_category}
Confidence: ${result.confidence_level}

Summary:
${result.summary}

Warning Signs:
${result.warning_signs.map((w) => `• ${w}`).join("\n")}

Recommendations:
${result.recommended_actions.map((a) => `- ${a}`).join("\n")}

Disclaimer:
${result.disclaimer}
Generated by FraudShield
    `.trim();

    await navigator.clipboard.writeText(report);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleFeedback = async (rating: 0 | 1) => {
    if (feedbackSent || feedbackLoading) return;
    setFeedbackLoading(true);
    try {
      await fetch("/api/fraudshield/feedback", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ scamCheckId: result.id, userRating: rating }),
      });
      setFeedbackSent(true);
    } catch {
      // Silent fail
    } finally {
      setFeedbackLoading(false);
    }
  };

  return (
    <div
      className="card-editorial rounded-2xl border border-[#E5E0D8] bg-white shadow-xs overflow-hidden animate-scale-in"
    >
      {/* Editorial Top Header Panel */}
      <div className="border-b border-[#E5E0D8] bg-[#FAF8F5] px-5 py-3.5 flex items-center justify-between gap-4">
        <div className="flex items-center gap-2">
          <Terminal className="h-4 w-4 text-[#11382B]" />
          <span className="text-xs font-bold text-black">
            Report <code className="text-black ml-1 font-mono font-bold">#fs-{result.id.slice(0, 6)}</code>
          </span>
        </div>
        <div className={`px-2.5 py-0.5 rounded-full text-xs font-bold border ${statusColor}`}>
          {result.risk_level}
        </div>
      </div>

      <div className="p-5 sm:p-7 space-y-6">
        {/* 2-Column Dashboard Split */}
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
          {/* Left Metrics Column */}
          <div className="lg:col-span-5 flex flex-col items-center p-5 bg-[#FAF8F5] rounded-xl border border-[#E5E0D8]">
            <RiskGauge score={result.risk_score} riskLevel={result.risk_level} size={140} />

            {/* Info Table */}
            <div className="w-full mt-4 border-t border-[#E5E0D8] pt-3 space-y-2.5 text-xs">
              <div className="flex items-center justify-between pb-2.5 border-b border-[#E5E0D8]">
                <span className="font-bold text-black">Category</span>
                <div className="flex items-center gap-1.5 font-bold text-black">
                  <div className="p-1 rounded bg-white border border-[#E5E0D8] text-[#11382B] shrink-0">
                    <CategoryIcon category={result.scam_category} className="h-3.5 w-3.5" />
                  </div>
                  <span>{result.scam_category}</span>
                </div>
              </div>

              <div className="flex items-center justify-between">
                <span className="font-bold text-black">Confidence</span>
                <span className={`inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-xs font-bold border ${getConfidenceColor(result.confidence_level)}`}>
                  <Info className="h-3 w-3" />
                  {result.confidence_level}
                </span>
              </div>
            </div>
          </div>

          {/* Right Summary Column */}
          <div className="lg:col-span-7 space-y-3 h-full flex flex-col justify-center">
            <div className="flex items-center gap-1.5 text-black">
              <ShieldCheck className="h-4 w-4 text-[#11382B]" />
              <h3 className="text-xs font-bold uppercase tracking-wider text-black">Summary</h3>
            </div>
            <p className="text-black text-xs sm:text-sm leading-relaxed font-medium">
              {result.summary}
            </p>
            <div className="text-xs font-bold text-black border-t border-[#E5E0D8] pt-2.5 leading-normal flex items-start gap-1.5">
              <Info className="h-3.5 w-3.5 text-black shrink-0 mt-0.5" />
              Verified against active scam signatures and public databases.
            </div>
          </div>
        </div>

        {/* Detailed Findings Cards */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 pt-1 border-t border-[#E5E0D8]">
          {/* Warning Signs */}
          <div className="p-4 rounded-xl border border-[#FDE68A] bg-[#FEF3C7]/25 space-y-2.5">
            <h3 className="text-xs font-bold text-[#92400E] uppercase tracking-wide flex items-center gap-1.5">
              <AlertTriangle className="h-3.5 w-3.5 text-[#D97706]" />
              Warning Signs
            </h3>
            {result.warning_signs.length > 0 ? (
              <ul className="space-y-2">
                {result.warning_signs.map((sign, i) => (
                  <li key={i} className="flex items-start gap-2">
                    <span className="h-1.5 w-1.5 rounded-full bg-[#D97706] mt-1.5 shrink-0" />
                    <span className="text-xs text-black font-semibold leading-relaxed">{sign}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <div className="text-xs text-black font-medium">No warning signs detected.</div>
            )}
          </div>

          {/* Recommended Actions */}
          <div className="p-4 rounded-xl border border-[#BBF7D0] bg-[#F0FDF4]/50 space-y-2.5">
            <h3 className="text-xs font-bold text-[#166534] uppercase tracking-wide flex items-center gap-1.5">
              <CheckCircle className="h-3.5 w-3.5 text-[#166534]" />
              Recommended Steps
            </h3>
            {result.recommended_actions.length > 0 ? (
              <ul className="space-y-2">
                {result.recommended_actions.map((action, i) => (
                  <li key={i} className="flex items-start gap-2">
                    <Check className="h-3.5 w-3.5 text-[#166534] mt-0.5 shrink-0" />
                    <span className="text-xs text-black font-bold leading-relaxed">{action}</span>
                  </li>
                ))}
              </ul>
            ) : (
              <div className="text-xs text-black font-medium">No actions required.</div>
            )}
          </div>
        </div>

        {/* Community Threat Database Matches */}
        {result.matchingReports && result.matchingReports.length > 0 && (
          <div className="p-4 rounded-xl border border-[#FCA5A5] bg-[#FEF2F2]/30 space-y-3 pt-3 border-t">
            <div className="flex items-center gap-1.5">
              <Database className="h-4 w-4 text-[#DC2626]" />
              <h3 className="text-xs font-bold text-[#991B1B] uppercase tracking-wide">
                Community Reports ({result.matchingReports.length})
              </h3>
            </div>
            <p className="text-black text-xs font-medium leading-normal">
              Similar message reported by other users:
            </p>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              {result.matchingReports.map((report) => (
                <div
                  key={report.id}
                  className="p-3 rounded-xl border border-[#E5E0D8] bg-white space-y-2 text-xs"
                >
                  <div className="flex items-center justify-between gap-2 border-b border-[#E5E0D8] pb-1.5">
                    <span className="px-2 py-0.5 rounded-full bg-[#FEF2F2] border border-[#FECACA] text-[#991B1B] font-bold text-[11px]">
                      {report.category || "Scam Report"}
                    </span>
                    <span className="text-black flex items-center gap-1 font-bold text-[11px]">
                      <Calendar className="h-3 w-3" />
                      {new Date(report.createdAt).toLocaleDateString()}
                    </span>
                  </div>

                  <p className="text-black leading-relaxed line-clamp-3 font-medium">
                    &ldquo;{report.reportedMessage}&rdquo;
                  </p>

                  <div className="flex items-center justify-between gap-2 text-black border-t border-[#E5E0D8] pt-1.5 text-[11px] font-bold">
                    <span className="flex items-center gap-1">
                      <User className="h-3 w-3 text-black" />
                      {redactEmail(report.userEmail)}
                    </span>
                    {report.country && (
                      <span className="flex items-center gap-1">
                        <MapPin className="h-3 w-3 text-black" />
                        {report.country}
                      </span>
                    )}
                  </div>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Web Grounding Sources */}
        {result.sources && result.sources.length > 0 && (
          <div className="p-4 rounded-xl border border-[#E5E0D8] bg-white space-y-2.5">
            <div className="flex items-center justify-between">
              <h3 className="text-xs font-bold text-[#11382B] uppercase tracking-wide flex items-center gap-1.5">
                <Globe className="h-3.5 w-3.5 text-[#11382B]" />
                Verified Sources
              </h3>
              <span className="text-[11px] font-bold text-black bg-[#FAF8F5] px-2 py-0.5 rounded-md border border-[#E5E0D8]">
                {result.sources.length} Verified
              </span>
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
              {result.sources.slice(0, 4).map((source, i) => (
                <GroundingSourceItem key={i} text={source} />
              ))}
            </div>
          </div>
        )}

        {/* Footer Actions */}
        <div className="pt-4 border-t border-[#E5E0D8] flex flex-col sm:flex-row items-center justify-between gap-3">
          <div className="flex flex-wrap items-center gap-2 w-full sm:w-auto">
            <button
              onClick={handleCopy}
              className="w-full sm:w-auto flex items-center justify-center gap-1.5 px-4 py-2 rounded-xl btn-pine text-xs font-bold shadow-xs cursor-pointer"
            >
              <SaasCopyIcon copied={copied} />
            </button>
            <button
              onClick={onReset}
              className="w-full sm:w-auto flex items-center justify-center gap-1.5 px-4 py-2 rounded-xl bg-white text-black border-1.5 border-[#E5E0D8] hover:border-black hover:bg-[#FAF8F5] text-xs font-bold shadow-xs cursor-pointer transition-all"
            >
              <RotateCcw className="h-3.5 w-3.5 text-black" />
              New Scan
            </button>
          </div>

          <div className="flex items-center gap-2.5 self-end sm:self-auto text-xs text-black">
            <span className="font-bold">Helpful?</span>
            {feedbackSent ? (
              <span className="text-xs font-bold text-[#166534] flex items-center gap-1">
                <CheckCircle className="h-3.5 w-3.5" />
                Thanks!
              </span>
            ) : (
              <div className="flex items-center gap-1">
                <button
                  onClick={() => handleFeedback(1)}
                  disabled={feedbackLoading}
                  className="p-1.5 rounded-lg border border-[#E5E0D8] bg-white hover:bg-[#FAF8F5] text-black transition-all cursor-pointer"
                  aria-label="Thumbs Up"
                >
                  <ThumbsUp className="h-3.5 w-3.5 text-black" />
                </button>
                <button
                  onClick={() => handleFeedback(0)}
                  disabled={feedbackLoading}
                  className="p-1.5 rounded-lg border border-[#E5E0D8] bg-white hover:bg-[#FAF8F5] text-black transition-all cursor-pointer"
                  aria-label="Thumbs Down"
                >
                  <ThumbsDown className="h-3.5 w-3.5 text-black" />
                </button>
              </div>
            )}
          </div>
        </div>

        <div className="mt-2 text-xs text-black font-medium bg-[#FAF8F5] p-3 rounded-xl border border-[#E5E0D8] leading-relaxed">
          {result.disclaimer}
        </div>
      </div>
    </div>
  );
}

function SaasCopyIcon({ copied }: { copied: boolean }) {
  if (copied) {
    return (
      <>
        <Check className="h-3.5 w-3.5 text-white animate-scale-in" />
        Copied
      </>
    );
  }
  return (
    <>
      <Copy className="h-3.5 w-3.5" />
      Copy Report
    </>
  );
}
