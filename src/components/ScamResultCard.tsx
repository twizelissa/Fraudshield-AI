interface ScamResultCardProps {
  result: ScamAnalysis & {
    id: string;
    matchingReports?: {
      id: string;
      reportedMessage: string;
      category: string | null;
      country: string | null;
      userEmail: string | null;
      createdAt: string;
    }[];
  };
  onReset: () => void;
}

const categoryIconMap: Record<string, React.ComponentType<{ className?: string }>> = {
  "fake job": Briefcase,
  "job": Briefcase,
  "fake scholarship": GraduationCap,
  "scholarship": GraduationCap,
  "fake grant": Building2,
  "grant": Building2,
  "phishing": Link2Off,
  "link": Link2Off,
  "fake investment": DollarSign,
  "investment": DollarSign,
  "finance": DollarSign,
  "romance/social scam": Heart,
  "romance": Heart,
  "social scam": Heart,
  "fake delivery/payment scam": Package,
  "delivery": Package,
  "payment": Package,
  "general suspicious message": AlertCircle,
  "suspicious sms": FileWarning,
  "sms": FileWarning,
  "whatsapp": FileWarning,
  "email": Mail,
  "unknown": HelpCircle,
};

function CategoryIcon({ category, className }: { category: string; className?: string }) {
  const normalized = category.toLowerCase().trim();
  let Icon: React.ComponentType<{ className?: string }> = Shield;
  for (const [key, iconComp] of Object.entries(categoryIconMap)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      Icon = iconComp;
      break;
    }
  }
  return <Icon className={className} />;
}

function GroundingSourceItem({ text }: { text: string }) {
  const urlRegex = /(https?:\/\/[^\s]+)/g;
  const parts = text.split(urlRegex);
  
  return (
    <div className="flex items-start gap-2.5">
      <Globe className="h-3.5 w-3.5 text-blue-brand shrink-0 mt-0.5" />
      <span className="text-xs text-slate-300 font-medium leading-relaxed">
        {parts.map((part, index) => {
          if (part.match(urlRegex)) {
            return (
              <a
                key={index}
                href={part}
                target="_blank"
                rel="noopener noreferrer"
                className="text-blue-brand font-bold underline hover:text-blue-400 transition-colors inline-flex items-center gap-0.5 break-all"
              >
                {part}
                <ExternalLink className="h-3 w-3 inline shrink-0" />
              </a>
            );
          }
          return part;
        })}
      </span>
    </div>
  );
}

function getConfidenceColor(level: string) {
  switch (level) {
    case "High":
      return "text-blue-400 bg-blue-500/5 border-blue-500/20 shadow-[0_0_10px_rgba(0,242,254,0.05)]";
    case "Medium":
      return "text-indigo-400 bg-indigo-500/5 border-indigo-500/20 shadow-[0_0_10px_rgba(79,70,229,0.05)]";
    default:
      return "text-slate-400 bg-slate-500/5 border-slate-500/10";
  }
}

const redactEmail = (email: string | null) => {
  if (!email) return "Anonymous Submitter";
  const parts = email.split("@");
  if (parts.length !== 2) return "Redacted Operator";
  const [username, domain] = parts;
  if (username.length <= 2) {
    return `${username}***@${domain}`;
  }
  return `${username.slice(0, 2)}***@${domain}`;
};

export default function ScamResultCard({ result, onReset }: ScamResultCardProps) {
  const [copied, setCopied] = useState(false);
  const [feedbackSent, setFeedbackSent] = useState(false);
  const [feedbackLoading, setFeedbackLoading] = useState(false);

  const isHighRisk = result.risk_level === "High Risk";
  const isMediumRisk = result.risk_level === "Medium Risk";

  const statusColor = isHighRisk
    ? "text-violet-400 bg-violet-500/5 border-violet-500/20 shadow-[0_0_15px_rgba(217,70,239,0.05)]"
    : isMediumRisk
    ? "text-indigo-400 bg-indigo-500/5 border-indigo-500/20 shadow-[0_0_15px_rgba(79,70,229,0.05)]"
    : "text-blue-400 bg-blue-500/5 border-blue-500/20 shadow-[0_0_15px_rgba(0,242,254,0.05)]";

  const handleCopy = async () => {
    const report = `
FraudShield AI Security Assessment
======================================
Report ID: ${result.id}
Risk Score: ${result.risk_score}/100
Risk Level: ${result.risk_level}
Category: ${result.scam_category}
Confidence: ${result.confidence_level}

Summary:
${result.summary}

Warning Signs Detected:
${result.warning_signs.map((w) => `• ${w}`).join("\n")}

Security Recommendations:
${result.recommended_actions.map((a) => `✓ ${a}`).join("\n")}

Disclaimer:
${result.disclaimer}
Generated by FraudShield AI
    `.trim();

    await navigator.clipboard.writeText(report);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleFeedback = async (rating: 0 | 1) => {
    if (feedbackSent || feedbackLoading) return;
    setFeedbackLoading(true);
    try {
      await fetch("/api/fraudshield/feedback", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ scamCheckId: result.id, userRating: rating }),
      });
      setFeedbackSent(true);
    } catch {
      // Silent fail
    } finally {
      setFeedbackLoading(false);
    }
  };

  return (
    <div
      className="glass-card rounded-3xl border border-blue-brand/20 bg-navy-dark/90 shadow-2xl overflow-hidden animate-scale-in"
    >
      {/* Console Top Header Panel */}
      <div className="border-b border-blue-brand/10 bg-navy/40 backdrop-blur-md px-6 py-4 flex items-center justify-between gap-4">
        <div className="flex items-center gap-2">
          <Terminal className="h-4 w-4 text-blue-brand animate-flicker" />
          <span className="text-[10px] font-bold text-blue-brand uppercase tracking-widest font-mono">
            threat matrix <code className="font-mono text-slate-500 ml-1">#fs-{result.id.slice(0, 6)}</code>
          </span>
        </div>
        <div className={`px-3 py-1 rounded-md text-[9px] font-bold border uppercase tracking-widest font-mono ${statusColor}`}>
          {result.risk_level}
        </div>
      </div>

      <div className="p-6 sm:p-8 space-y-8">
        {/* Holographic 2-Column Dashboard Split */}
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">
            {/* Left Metrics Column */}
            <div className="lg:col-span-5 flex flex-col items-center p-6 bg-navy/80 rounded-2xl border border-blue-brand/10 shadow-inner relative overflow-hidden">
                <div className="absolute inset-0 bg-[radial-gradient(circle_at_50%_-10%,rgba(0,242,254,0.02),transparent_60%)] pointer-events-none" />
                <RiskGauge score={result.risk_score} riskLevel={result.risk_level} size={150} />
                
                {/* Minimalist Info Table */}
                <div className="w-full mt-6 border-t border-blue-brand/10 pt-5 space-y-4 font-mono">
                    <div className="flex items-center justify-between pb-3.5 border-b border-blue-brand/5">
                        <span className="text-[9px] font-bold text-slate-500 uppercase tracking-widest">threat type</span>
                        <div className="flex items-center gap-3 text-xs font-bold text-white">
                             {/* Breathtaking double-bordered cyber-icon-panel */}
                             <div className="cyber-icon-panel p-2 rounded-xl text-blue-brand shrink-0">
                                  <CategoryIcon category={result.scam_category} className="h-4 w-4 animate-pulse" />
                             </div>
                             <span className="uppercase tracking-wider text-[10px]">{result.scam_category}</span>
                        </div>
                    </div>
                    
                    <div className="flex items-center justify-between">
                        <span className="text-[9px] font-bold text-slate-500 uppercase tracking-widest">Confidence</span>
                        <span className={`inline-flex items-center gap-1 px-2.5 py-1 rounded-md text-[9px] font-bold border uppercase tracking-wider ${getConfidenceColor(result.confidence_level)}`}>
                            <Info className="h-3 w-3" />
                            {result.confidence_level}
                        </span>
                    </div>
                </div>
            </div>

            {/* Right Summary Column */}
            <div className="lg:col-span-7 space-y-5 h-full flex flex-col justify-center">
                <div className="flex items-center gap-2 text-white">
                    <div className="h-7 w-7 rounded-lg bg-blue-brand/5 text-blue-brand border border-blue-brand/15 flex items-center justify-center shadow-sm">
                         <ShieldCheck className="h-4 w-4 animate-flicker" />
                    </div>
                    <h3 className="text-xs font-bold uppercase tracking-widest font-mono text-blue-brand">Executive Analysis Summary</h3>
                </div>
                <p className="text-slate-300 text-sm sm:text-[15px] leading-relaxed font-medium">
                  {result.summary}
                </p>
                <div className="text-[9px] font-medium text-slate-500 border-t border-blue-brand/5 pt-4 leading-normal flex items-start gap-2 italic font-mono">
                  <Info className="h-3.5 w-3.5 text-slate-500 shrink-0 mt-0.5" />
                  ANALYSIS RUN COMPLETED: Decoupled metadata triggers and checked linguistic models against decentralized database.
                </div>
            </div>
        </div>

        {/* Detailed Findings Cards */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6 pt-2 border-t border-blue-brand/10">
            {/* Warning Signs */}
            <div className="p-5 rounded-2xl border border-violet-950/50 bg-violet-950/10 space-y-4">
                <h3 className="text-[9px] font-bold text-violet-400 uppercase tracking-widest flex items-center gap-2 font-mono">
                    <AlertTriangle className="h-4 w-4 text-violet-400 animate-pulse" />
                    Threat Indicators Detected
                </h3>
                {result.warning_signs.length > 0 ? (
                    <ul className="space-y-3">
                        {result.warning_signs.map((sign, i) => (
                            <li key={i} className="flex items-start gap-2.5">
                                <span className="h-1.5 w-1.5 rounded-full bg-violet-500 mt-2 shrink-0 animate-pulse shadow-[0_0_8px_#d946ef]" />
                                <span className="text-xs text-slate-300 font-medium leading-relaxed">{sign}</span>
                            </li>
                        ))}
                    </ul>
                ) : (
                    <div className="text-xs text-slate-500 italic">No significant risk indicators identified.</div>
                )}
            </div>

            {/* Recommended Actions */}
            <div className="p-5 rounded-2xl border border-blue-950/50 bg-blue-950/10 space-y-4">
                <h3 className="text-[9px] font-bold text-blue-400 uppercase tracking-widest flex items-center gap-2 font-mono">
                    <CheckCircle className="h-4 w-4 text-blue-400 animate-pulse" />
                    Security Protocol Actions
                </h3>
                {result.recommended_actions.length > 0 ? (
                    <ul className="space-y-3">
                        {result.recommended_actions.map((action, i) => (
                            <li key={i} className="flex items-start gap-2.5">
                                <Check className="h-3.5 w-3.5 text-blue-400 mt-0.5 shrink-0 shadow-[0_0_8px_#00f2fe]" />
                                <span className="text-xs text-blue-300 font-semibold leading-relaxed">{action}</span>
                            </li>
                        ))}
                    </ul>
                ) : (
                    <div className="text-xs text-slate-500 italic">No immediate actions required.</div>
                )}
            </div>
        </div>

        {/* Community Threat Database Matches */}
        {result.matchingReports && result.matchingReports.length > 0 && (
            <div className="p-5 rounded-2xl border border-red-500/20 bg-red-950/5 space-y-4 pt-4 border-t border-red-500/10">
                <div className="flex items-center gap-2">
                    <Database className="h-4.5 w-4.5 text-red-500 animate-pulse" />
                    <h3 className="text-[10px] font-mono font-black text-red-400 uppercase tracking-widest flex items-center gap-2">
                        Community Threat Database Alerts Detected ({result.matchingReports.length})
                    </h3>
                </div>
                <p className="text-slate-400 text-[11px] font-mono leading-normal">
                    This payload matches active signatures cataloged from user-submitted threat reports.
                </p>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                    {result.matchingReports.map((report) => (
                        <div
                            key={report.id}
                            className="p-4 rounded-xl border border-red-500/10 bg-navy-dark/80 space-y-3 font-mono text-[9px]"
                        >
                            <div className="flex items-center justify-between gap-2 border-b border-red-500/5 pb-2">
                                <span className="px-2 py-0.5 rounded bg-red-500/10 border border-red-500/20 text-red-400 font-bold uppercase tracking-wider text-[8px]">
                                    {report.category || "General Threat"}
                                </span>
                                <span className="text-slate-500 flex items-center gap-1 font-medium">
                                    <Calendar className="h-3 w-3" />
                                    {new Date(report.createdAt).toLocaleDateString()}
                                </span>
                            </div>
                            
                            <p className="text-slate-300 leading-normal line-clamp-3 italic">
                                &ldquo;{report.reportedMessage}&rdquo;
                            </p>

                            <div className="flex items-center justify-between gap-3 text-slate-500 border-t border-red-500/5 pt-2">
                                <span className="flex items-center gap-1">
                                    <User className="h-3 w-3 text-red-400/40" />
                                    {redactEmail(report.userEmail)}
                                </span>
                                {report.country && (
                                    <span className="flex items-center gap-1">
                                        <MapPin className="h-3 w-3 text-violet-brand/40" />
                                        {report.country}
                                    </span>
                                )}
                            </div>
                        </div>
                    ))}
                </div>
            </div>
        )}

        {/* Web Intelligence Grounding Sources */}
        {result.sources && result.sources.length > 0 && (
            <div className="p-5 rounded-2xl border border-blue-brand/10 bg-navy/80 space-y-4 pt-4 border-t border-blue-brand/5">
                <h3 className="text-[9px] font-bold text-blue-brand uppercase tracking-widest flex items-center gap-2 font-mono">
                    <Globe className="h-4 w-4 text-blue-brand animate-pulse" />
                    Web Intelligence Grounding Matches
                </h3>
                <ul className="space-y-3">
                    {result.sources.map((source, i) => (
                        <li key={i} className="list-none">
                            <GroundingSourceItem text={source} />
                        </li>
                    ))}
                </ul>
            </div>
        )}

        {/* Footer Actions */}
        <div className="pt-6 border-t border-blue-brand/10 flex flex-col sm:flex-row items-center justify-between gap-5">
            <div className="flex flex-wrap items-center gap-2.5 w-full sm:w-auto">
                <button
                    onClick={handleCopy}
                    className="w-full sm:w-auto flex items-center justify-center gap-1.5 px-5 py-2.5 rounded-xl btn-cyber text-xs font-black uppercase tracking-widest shadow-lg cursor-pointer"
                >
                    <SaasCopyIcon copied={copied} />
                </button>
                <button
                    onClick={onReset}
                    className="w-full sm:w-auto flex items-center justify-center gap-1.5 px-5 py-2.5 rounded-xl border border-blue-brand/15 bg-navy-dark text-blue-brand text-xs font-semibold hover:bg-white/5 hover:scale-105 active:scale-95 transition-all duration-200 cursor-pointer uppercase tracking-widest font-mono text-[10px]"
                >
                    <RotateCcw className="h-3.5 w-3.5" />
                    Reset Console
                </button>
            </div>

            <div className="flex items-center gap-3.5 self-end sm:self-auto font-mono text-[9px]">
                <span className="text-slate-500 uppercase tracking-widest">Verify assessment?</span>
                {feedbackSent ? (
                    <span className="text-[10px] font-bold text-blue-brand uppercase tracking-wider flex items-center gap-1">
                      <CheckCircle className="h-3.5 w-3.5" />
                      Feedback Sent
                    </span>
                ) : (
                    <div className="flex items-center gap-1.5">
                        <button
                            onClick={() => handleFeedback(1)}
                            disabled={feedbackLoading}
                            className="p-2 rounded-lg border border-blue-brand/10 bg-navy-dark hover:border-blue-brand hover:bg-blue-brand/10 hover:text-blue-brand transition-all duration-200 cursor-pointer"
                            aria-label="Thumbs Up"
                        >
                            <ThumbsUp className="h-3.5 w-3.5" />
                        </button>
                        <button
                            onClick={() => handleFeedback(0)}
                            disabled={feedbackLoading}
                            className="p-2 rounded-lg border border-blue-brand/10 bg-navy-dark hover:border-violet-brand hover:bg-violet-brand/10 hover:text-violet-brand transition-all duration-200 cursor-pointer"
                            aria-label="Thumbs Down"
                        >
                            <ThumbsDown className="h-3.5 w-3.5" />
                        </button>
                    </div>
                )}
            </div>
        </div>

        <div className="mt-4 flex items-start gap-2.5 text-[9px] text-slate-500 bg-slate-900/50 p-3.5 rounded-xl border border-blue-brand/5 leading-normal italic font-mono">
          <Info className="h-3.5 w-3.5 shrink-0 text-slate-500" />
          {result.disclaimer}
        </div>
      </div>
    </div>
  );
}

function SaasCopyIcon({ copied }: { copied: boolean }) {
  if (copied) {
    return (
      <>
        <Check className="h-3.5 w-3.5 text-navy animate-scale-in" />
        Report Copied
      </>
    );
  }
  return (
    <>
      <Copy className="h-3.5 w-3.5" />
      Copy Full Report
    </>
  );
}
